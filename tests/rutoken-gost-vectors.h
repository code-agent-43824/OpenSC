struct gost_vko_vector {
	const char *source;
	CK_MECHANISM_TYPE mechanism;
	CK_KEY_TYPE key_type;
	const CK_BYTE *paramset;
	CK_ULONG paramset_len;
	const CK_BYTE *private_key;
	CK_ULONG private_len;
	const CK_BYTE *peer_public;
	CK_ULONG public_len;
	const CK_BYTE *ukm;
	CK_ULONG ukm_len;
	const CK_BYTE *result;
	CK_ULONG result_len;
};

#define GOST_VKO_ENTRY(source, mechanism, key_type, paramset, private_key, \
		peer, ukm, result) \
	{ source, mechanism, key_type, paramset, sizeof(paramset), private_key, \
	  sizeof(private_key), peer, sizeof(peer), ukm, sizeof(ukm), result, \
	  sizeof(result) }

